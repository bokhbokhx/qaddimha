export function wrapDocuments(docs: { name: string; chunks: { locator: string; text: string }[] }[]) {
  return docs
    .map(
      (d) =>
        `<document name="${d.name.replace(/"/g, "'")}">\n${d.chunks.map((c) => `<chunk locator="${c.locator}">\n${c.text}\n</chunk>`).join("\n")}\n</document>`,
    )
    .join("\n");
}

